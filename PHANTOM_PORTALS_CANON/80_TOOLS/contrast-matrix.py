#!/usr/bin/env python3
"""Compute WCAG 2.2 contrast for every token text/surface pairing and write
10_DESIGN_SYSTEM/accessibility/contrast-matrix.md.

Reads the built tokens (10_DESIGN_SYSTEM/tokens/build/tokens.resolved.json), so
run build-tokens first. Stdlib only. Exit code 1 if an approved pairing fails.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / '10_DESIGN_SYSTEM/tokens/build/tokens.resolved.json'
OUT = ROOT / '10_DESIGN_SYSTEM/accessibility/contrast-matrix.md'

# The spec's approved text pairings (README "Accessibility") plus the derived ones the system relies on.
APPROVED = [
    ('ink-primary', 'surface-primary', 'text'), ('ink-primary', 'surface-canvas', 'text'),
    ('ink-on-inverse', 'surface-inverse', 'text'), ('accent-crimson', 'surface-primary', 'text'),
    ('ink-on-inverse', 'accent-crimson', 'text'), ('ink-on-inverse', 'accent-hero', 'text'),
    ('ink-secondary', 'surface-primary', 'text'), ('ink-secondary', 'surface-canvas', 'text'),
    ('ink-secondary', 'surface-sunken', 'text'), ('ink-on-inverse-secondary', 'surface-inverse', 'text'),
    ('accent-crimson-on-inverse', 'surface-inverse', 'text'), ('ink-on-inverse', 'accent-crimson-pressed', 'text'),
    ('ink-primary', 'surface-crimson-soft', 'text'), ('accent-crimson', 'surface-crimson-soft', 'text'),
    ('status-success', 'surface-primary', 'text'), ('status-warning', 'surface-primary', 'text'),
    ('border-control', 'surface-primary', 'ui'), ('border-control', 'surface-canvas', 'ui'),
    ('border-inverse', 'surface-inverse', 'ui'), ('focus-ring', 'surface-primary', 'ui'),
    ('focus-ring-inverse', 'surface-inverse', 'ui'),
]
# Pairings that must NOT be used for text; listed so nobody rediscovers them the hard way.
FORBIDDEN = [('accent-electric', 'surface-primary', 'Decorative only — never text on light.'),
             ('accent-crimson', 'surface-inverse', 'Use accent-crimson-on-inverse on black.'),
             ('border-default', 'surface-primary', 'Never the only boundary of a control.')]


def rgba(value):
    v = value.strip().lower()
    if v.startswith('#'):
        h = v[1:]
        if len(h) == 3:
            h = ''.join(c * 2 for c in h)
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (1.0,)
    m = re.match(r'rgba?\(([^)]*)\)', v)
    parts = [float(p) for p in m.group(1).split(',')]
    return tuple(parts[:3]) + ((parts[3] if len(parts) > 3 else 1.0),)


def over(fg, bg):
    a = fg[3]
    return tuple(fg[i] * a + bg[i] * (1 - a) for i in range(3)) + (1.0,)


def luminance(c):
    def ch(x):
        x /= 255
        return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4
    r, g, b = (ch(x) for x in c[:3])
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def verdict(r, kind):
    if kind == 'ui':
        return 'PASS (≥3:1 UI)' if r >= 3 else 'FAIL'
    if r >= 7:
        return 'AAA'
    if r >= 4.5:
        return 'AA'
    if r >= 3:
        return 'AA large only'
    return 'FAIL'


def main():
    tokens = json.loads(TOKENS.read_text())
    colors = {k: v['value'] for k, v in tokens.items() if v['type'] == 'color'}

    def resolve(name, seen=()):
        v = colors[name]
        m = re.fullmatch(r'\{([\w.-]+)\}', v)
        return resolve(m.group(1).replace('.', '-'), seen + (name,)) if m else v

    solid = {k: rgba(resolve(k)) for k in colors}
    fgs = [k for k in solid if k.startswith(('ink-', 'accent-', 'status-', 'border-')) and solid[k][3] == 1]
    bgs = [k for k in solid if k.startswith('surface-')] + ['accent-crimson', 'accent-hero', 'accent-crimson-pressed']

    lines = ['# Contrast matrix', '',
             '> GENERATED by `80_TOOLS/contrast-matrix.py` from the built tokens. Do not edit; rebuild.', '',
             'WCAG 2.2 contrast ratios (relative luminance, sRGB). Text needs **4.5:1** (AA) or **3:1** at 24 px+ / 18.66 px bold;',
             'UI boundaries and focus indicators need **3:1**. AAA is 7:1.', '',
             '## Approved pairings', '', '| foreground | background | use | ratio | result |', '|---|---|---|---:|---|']
    failures = []
    for fg, bg, kind in APPROVED:
        r = ratio(solid[fg], solid[bg])
        res = verdict(r, kind)
        if res == 'FAIL' or (kind == 'text' and r < 4.5):
            failures.append(f'{fg} on {bg}: {r:.2f}')
        lines.append(f'| `{fg}` | `{bg}` | {kind} | {r:.2f}:1 | {res} |')
    lines += ['', '## Never use for text', '', '| foreground | background | ratio | why |', '|---|---|---:|---|']
    for fg, bg, why in FORBIDDEN:
        lines.append(f'| `{fg}` | `{bg}` | {ratio(solid[fg], solid[bg]):.2f}:1 | {why} |')

    lines += ['', '## Glass over artwork (worst case)', '',
              '`overlay-glass` composited over pure ink (`#151519`), the darkest thing the art can put behind it:', '',
              '| text | on glass over ink | result |', '|---|---:|---|']
    glass = over(rgba(resolve('overlay-glass')), solid['surface-inverse'])
    for fg in ('ink-primary', 'ink-secondary', 'accent-crimson'):
        r = ratio(solid[fg], glass)
        lines.append(f'| `{fg}` | {r:.2f}:1 | {verdict(r, "text")} |')

    lines += ['', '## Full matrix (foreground rows × background columns)', '',
              '| | ' + ' | '.join(f'`{b}`' for b in bgs) + ' |', '|---|' + '---:|' * len(bgs)]
    for fg in fgs:
        lines.append(f'| `{fg}` | ' + ' | '.join(f'{ratio(solid[fg], solid[b]):.2f}' for b in bgs) + ' |')
    lines.append('')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines))
    print(f'Wrote {OUT.relative_to(ROOT)} — {len(APPROVED)} approved pairings, {len(failures)} failing')
    for f in failures:
        print('  FAIL', f)
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
