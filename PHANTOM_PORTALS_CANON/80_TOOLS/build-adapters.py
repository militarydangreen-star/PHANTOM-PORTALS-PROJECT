FIGMA_SCOPE = {'surface': ['FRAME_FILL', 'SHAPE_FILL'], 'ink': ['TEXT_FILL', 'SHAPE_FILL'], 'accent': ['ALL_FILLS', 'STROKE_COLOR'],
               'border': ['STROKE_COLOR'], 'status': ['ALL_FILLS', 'STROKE_COLOR'], 'focus': ['STROKE_COLOR'], 'overlay': ['FRAME_FILL', 'EFFECT_COLOR']}


def _role_scope(role):
    if role.endswith('foreground'):
        return ['TEXT_FILL', 'SHAPE_FILL']
    if role in ('border', 'input', 'ring') or role.endswith(('-border', '-ring')):
        return ['STROKE_COLOR']
    if role.startswith('chart'):
        return ['SHAPE_FILL', 'STROKE_COLOR']
    return ['FRAME_FILL', 'SHAPE_FILL']


def _resolve(ref):
    m = re.fullmatch(r'\{(.+)\}', str(ref))
    if not m:
        return ref
    node = SRC
    for part in m.group(1).split('.'):
        node = node[part]
    return _resolve(node['$value'])


def _px(v):
    return float(str(v).replace('px', ''))


def text_styles():
    out = []
    weight_name = {400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold'}
    for key, tok in SRC['text'].items():
        if key.startswith('$'):
            continue
        v = tok['$value']
        fam = _resolve(v['fontFamily'])
        fam = fam[0] if isinstance(fam, list) else fam.split(',')[0].strip('"\' ')
        size = _px(_resolve(v['fontSize']))
        lh = _resolve(v['lineHeight'])
        ls = str(_resolve(v.get('letterSpacing', '0')))
        ls_pct = float(ls.replace('em', '')) * 100 if ls.endswith('em') else 0.0
        out.append({'name': f'Phantom/{key}', 'cssToken': f'--text-{key}', 'fontFamily': fam,
                    'fontStyle': weight_name.get(int(_resolve(v['fontWeight'])), 'Regular'), 'fontSize': size,
                    'lineHeight': {'unit': 'PIXELS', 'value': _px(lh)} if 'px' in str(lh) else {'unit': 'PERCENT', 'value': float(lh) * 100},
                    'letterSpacing': {'unit': 'PERCENT', 'value': round(ls_pct, 2)},
                    # Case is not a token; the library uppercases only the eyebrow (.pp-eyebrow), so Figma matches that.
                    'textCase': 'UPPER' if key == 'eyebrow' else 'ORIGINAL'})
    return out


def effect_styles():
    out = []
    for name, t in RES.items():
        if t['type'] != 'shadow':
            continue
        layers = []
        for layer in re.split(r',\s*(?![^()]*\))', t['value']):
            inset = layer.strip().startswith('inset')
            nums = re.findall(r'-?[\d.]+px|\b0\b', layer.replace('inset', ''))
            x, y, blur, spread = (float(n.replace('px', '')) for n in (nums + ['0'] * 4)[:4])
            col = re.search(r'rgba?\(([^)]*)\)|#[0-9a-fA-F]{6}', layer).group(0)
            if col.startswith('#'):
                r, g, b, a = (*[int(col[i:i + 2], 16) / 255 for i in (1, 3, 5)], 1.0)
            else:
                parts = [float(p) for p in re.search(r'\(([^)]*)\)', col).group(1).split(',')]
                r, g, b = (p / 255 for p in parts[:3])
                a = parts[3] if len(parts) > 3 else 1.0
            layers.append({'type': 'INNER_SHADOW' if inset else 'DROP_SHADOW', 'offset': {'x': x, 'y': y}, 'radius': blur, 'spread': spread,
                           'color': {'r': round(r, 4), 'g': round(g, 4), 'b': round(b, 4), 'a': round(a, 4)}})
        out.append({'name': f'Phantom/{name}', 'cssToken': f'--{name}', 'effects': layers})
    return out


def build_figma():
    prim = []
    for name, t in RES.items():
        if t['type'] != 'color' or not re.fullmatch(r'#[0-9a-fA-F]{6}', t['value']):
            continue
        group = t['path'].split('.')[0]
        prim.append({'name': 'color/' + t['path'].replace('.', '/'), 'type': 'COLOR', 'value': t['value'].upper(),
                     'scopes': [], 'codeSyntax': {'WEB': f'var(--{name})'}, 'token': name})
    overlays = [{'name': 'color/' + t['path'].replace('.', '/'), 'type': 'COLOR', 'value': t['value'], 'scopes': FIGMA_SCOPE['overlay'],
                 'codeSyntax': {'WEB': f'var(--{n})'}, 'token': n} for n, t in RES.items() if t['type'] == 'color' and t['value'].startswith('rgba')]
    semantic = []
    for role in SHADCN['light']:
        semantic.append({'name': f'color/{role}', 'type': 'COLOR', 'scopes': _role_scope(role), 'codeSyntax': {'WEB': f'var(--{role})'},
                         'values': {'Light': {'alias': 'color/' + RES[SHADCN['light'][role]]['path'].replace('.', '/')},
                                    'Inverse': {'alias': 'color/' + RES[SHADCN['dark'][role]]['path'].replace('.', '/')}}})
    floats = []
    for name, t in RES.items():
        if t['type'] not in ('dimension',):
            continue
        group = t['path'].split('.')[0]
        scope = {'space': ['GAP'], 'radius': ['CORNER_RADIUS'], 'chamfer': [], 'stroke': ['STROKE_FLOAT']}.get(group, ['WIDTH_HEIGHT'])
        val = 999.0 if t['value'] in ('9999px', '999px') else _px(t['value'])
        floats.append({'name': t['path'].replace('.', '/'), 'type': 'FLOAT', 'value': val, 'scopes': scope, 'codeSyntax': {'WEB': f'var(--{name})'}, 'token': name})
    spec = {
        '_generated': HEADER,
        'file': {'name': 'Phantom Portals — Design System', 'pages': ['Cover', 'Getting started', 'Foundations', 'Components', 'Templates', '_Scratch']},
        'collections': [
            {'name': 'Primitives', 'modes': ['Value'], 'note': 'Raw canon colours; hidden from pickers (scopes []).', 'variables': prim + overlays},
            {'name': 'Color', 'modes': ['Light', 'Inverse'], 'note': 'Semantic roles, same names as the shadcn CSS variables. Inverse = black architecture regions. A second mode needs a Figma Professional plan or higher.',
             'variables': semantic},
            {'name': 'Dimension', 'modes': ['Value'], 'note': 'Space, radius, chamfer, stroke and shell sizes in px.', 'variables': floats},
        ],
        'textStyles': text_styles(),
        'effectStyles': effect_styles(),
        'components_v1': ['Button (primary, secondary, ghost, danger × default, hover, focus, pressed, disabled)', 'IconButton', 'Omnibox', 'Tabs', 'Toggle',
                          'Select', 'StatusBadge (ok, warn, error, run, idle)', 'Notification (ok, warn, error, info)', 'Progress', 'Tooltip',
                          'TabStrip', 'BookmarksBar', 'UtilityRail', 'ToolTile', 'StatusPanel', 'Terminal', 'PhantomHero'],
    }
    return {'figma/figma-variables.json': dump_json(spec)}


