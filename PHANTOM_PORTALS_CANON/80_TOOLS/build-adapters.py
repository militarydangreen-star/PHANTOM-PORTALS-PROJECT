# ---------------------------------------------------------------- contrast report
def contrast_report():
    lines, failures = [f'<!-- {HEADER} -->', '# Adapter contrast (WCAG 2.2)', '',
                       'Every foreground/background pairing the shadcn theme and the Figma `Color` collection create. `light` is the white-forward UI; `dark` is the inverse regions. Minimum 4.5:1 for text, 3:1 for component boundaries and focus rings.', ''], []
    for mode in ('light', 'dark'):
        lines += [f'## {mode}', '', '| Foreground | Background | Ratio | Min | Use | Result |', '|---|---|---:|---:|---|---|']
        for fg, bg, need, why in PAIRS + (LIGHT_ONLY if mode == 'light' else []):
            a, b = hexv(SHADCN[mode][fg]), hexv(SHADCN[mode][bg])
            r = contrast(a, b)
            ok = r >= need
            if not ok:
                failures.append(f'{mode}: {fg} on {bg} = {r:.2f} < {need}')
            lines.append(f'| `{fg}` {a} | `{bg}` {b} | {r:.2f} | {need} | {why} | {"PASS" if ok else "**FAIL**"} |')
        lines.append('')
    lines += ['Status colours (`success`, `warning`) are only used on light chips: in `dark` regions status badges keep their white chip, as the component library does.', '']
    return {'CONTRAST.md': '\n'.join(lines)}, failures


def main():
    # Prove the oklch conversion is exact for every colour token before writing anything.
    bad = [(n, t['value'], oklch_to_hex(oklch(t['value'].upper()))) for n, t in RES.items()
           if t['type'] == 'color' and re.fullmatch(r'#[0-9a-fA-F]{6}', t['value']) and oklch_to_hex(oklch(t['value'].upper())) != t['value'].upper()]
    if bad:
        print('oklch round-trip failed:', bad)
        return 1
