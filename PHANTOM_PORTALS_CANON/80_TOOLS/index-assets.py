#!/usr/bin/env python3
"""Scan 30_ASSETS sidecars (*.meta.json) and write 30_ASSETS/INDEX.json.

  python3 80_TOOLS/index-assets.py            # rebuild the index
  python3 80_TOOLS/index-assets.py --check    # exit 1 if the index is stale or a file drifted from its sidecar
  python3 80_TOOLS/index-assets.py --new path/to/file.svg --id PP-VEC-020 --title "…" [--kind vector] [--status CURRENT]
                                              # write a starter sidecar for a new asset, then rebuild

Every asset file needs a sidecar beside it named <file>.meta.json. The sidecar's
sha256 and bytes must match the file; the index records both so a release can
prove nothing changed silently.
"""
import argparse
import sys
from collections import Counter
from pathlib import Path

from canon_common import (CANON_VERSION, ROOT, sidecar_exempt, dump_json, load_sidecar, rel, sha256, sidecars, walk)

BASE = ROOT / '30_ASSETS'
INDEX = BASE / 'INDEX.json'
INDEX_JS = BASE / 'INDEX.js'  # same catalog as a script, for pages opened from disk (the gallery)


def build_index():
    entries, problems = [], []
    for side in sidecars(BASE):
        meta = load_sidecar(side)
        asset = side.with_name(side.name[:-len('.meta.json')])
        if not asset.exists():
            problems.append(f'{rel(side)}: sidecar without file')
            continue
        if meta.get('sha256') != sha256(asset) or meta.get('bytes') != asset.stat().st_size:
            problems.append(f'{rel(asset)}: file changed since its sidecar was written (update sha256/bytes)')
        entries.append({
            'id': meta['id'], 'path': rel(asset), 'title': meta['title'], 'status': meta['status'],
            'kind': meta['kind'], 'format': meta['format'], 'dimensions': meta.get('dimensions'),
            'bytes': meta['bytes'], 'sha256': meta['sha256'], 'tags': meta.get('tags', []), 'license': meta['license'],
        })
    for f in walk(BASE):
        if f.name.endswith('.meta.json') or sidecar_exempt(f):
            continue
        if not f.with_name(f.name + '.meta.json').exists():
            problems.append(f'{rel(f)}: no sidecar')
    ids = Counter(e['id'] for e in entries)
    problems += [f'duplicate id {i} ({n}×)' for i, n in ids.items() if n > 1]
    entries.sort(key=lambda e: e['path'])
    index = {
        'generated_by': '80_TOOLS/index-assets.py', 'canon_version': CANON_VERSION, 'count': len(entries),
        'by_status': dict(sorted(Counter(e['status'] for e in entries).items())),
        'by_kind': dict(sorted(Counter(e['kind'] for e in entries).items())),
        'total_bytes': sum(e['bytes'] for e in entries), 'assets': entries,
    }
    return index, problems


def new_sidecar(args):
    f = Path(args.new).resolve()
    side = f.with_name(f.name + '.meta.json')
    if side.exists():
        sys.exit(f'{rel(side)} already exists')
    side.write_text(dump_json({
        'id': args.id, 'file': f.name, 'title': args.title, 'status': args.status, 'canon_version': CANON_VERSION,
        'kind': args.kind, 'format': f.suffix.lstrip('.'), 'dimensions': None, 'bytes': f.stat().st_size,
        'sha256': sha256(f), 'usage': '', 'rules': [], 'tags': [],
        'license': 'Project-original artwork for Phantom Portals. Owner-controlled; all rights reserved by the project owner.',
        'source': {'origin': 'TODO: where this file came from (tool, prompt id, author, date)'},
    }))
    print(f'Wrote {rel(side)} — fill in usage, rules, tags and source.')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--new')
    ap.add_argument('--id')
    ap.add_argument('--title')
    ap.add_argument('--kind', default='vector')
    ap.add_argument('--status', default='DRAFT')
    args = ap.parse_args()
    if args.new:
        if not (args.id and args.title):
            sys.exit('--new needs --id and --title')
        new_sidecar(args)
    index, problems = build_index()
    text = dump_json(index)
    js = '// GENERATED by 80_TOOLS/index-assets.py — the 30_ASSETS catalog for offline pages. Do not edit.\nwindow.PhantomAssets = ' + text
    if args.check:
        stale = any(not f.exists() or f.read_text() != t for f, t in ((INDEX, text), (INDEX_JS, js)))
        for p in problems:
            print('  PROBLEM', p)
        if stale:
            print('  STALE 30_ASSETS/INDEX.json — run python3 80_TOOLS/index-assets.py')
        print(f'assets: {index["count"]} indexed, {len(problems)} problems{", index stale" if stale else ""}')
        return 1 if (problems or stale) else 0
    INDEX.write_text(text)
    INDEX_JS.write_text(js)
    print(f'Wrote 30_ASSETS/INDEX.json + INDEX.js — {index["count"]} assets, {index["total_bytes"] / 1e6:.1f} MB, {len(problems)} problems')
    for p in problems:
        print('  PROBLEM', p)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
