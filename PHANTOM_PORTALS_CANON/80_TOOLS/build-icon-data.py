#!/usr/bin/env python3
"""Write 10_DESIGN_SYSTEM/iconography/icons.data.js: the 20 UI icons as data: URIs.

The library renders UI icons as CSS masks. Browsers refuse mask images from
file:// (CORS), so pages opened straight from disk — the gallery, the HTML
starter, WinPE pages — load this script and pass the data URIs to
configureIcons(). Over http(s) plain file paths work too.

  python3 80_TOOLS/build-icon-data.py          # rebuild
  python3 80_TOOLS/build-icon-data.py --check  # exit 1 if stale
"""
import sys
from urllib.parse import quote

from canon_common import ROOT

SRC = ROOT / '10_DESIGN_SYSTEM/iconography/icons/svg'
OUT = ROOT / '10_DESIGN_SYSTEM/iconography/icons.data.js'


def render():
    lines = ['// GENERATED by 80_TOOLS/build-icon-data.py from iconography/icons/svg. Do not edit.',
             '// Usage: PhantomPortals.configureIcons(PhantomIconData);', 'window.PhantomIconData = {']
    for f in sorted(SRC.glob('*.svg')):
        svg = ' '.join(f.read_text().split())
        lines.append(f"  '{f.stem}': 'data:image/svg+xml,{quote(svg, safe='=:/,;.-')}',")
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main():
    text = render()
    if '--check' in sys.argv:
        stale = not OUT.exists() or OUT.read_text() != text
        print('icons.data.js', 'STALE — run python3 80_TOOLS/build-icon-data.py' if stale else 'current')
        return 1 if stale else 0
    OUT.write_text(text)
    print(f'Wrote {OUT.relative_to(ROOT)} ({text.count("data:")} icons, {len(text) // 1024} KB)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
